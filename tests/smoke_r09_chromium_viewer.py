"""Real headless Chrome desktop/mobile smoke for isolated R0.9 curiosity UI.

A disposable local SQLite journal is generated by the actual isolated CLI.
Only test-generated PRIVATE JSONL enters Chrome through the local file picker.
No internet access, browser package installs or production files are required.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

from smoke_real_chromium_viewer import (
    chrome_binary, inspect_actual_browser, inspect_actual_mobile_chromedriver,
)

ROOT = Path(__file__).resolve().parents[1]
VIEWER = ROOT / "examples/sensory_observer.html"


def instrument(original, jsonl):
    literal = json.dumps(jsonl, ensure_ascii=True).replace("<", "\\u003c")
    injected = r"""
<script>
window.addEventListener("load", async () => {
  const el = id => document.getElementById(id);
  try {
    const fixture = new File([__TRACE__], "local.synthetic.private.jsonl", {type:"text/plain"});
    const picker = el("trace");
    Object.defineProperty(picker, "files", {configurable:true, value:[fixture]});
    picker.dispatchEvent(new Event("change", {bubbles:true}));
    let ready = false;
    for (let n=0; n<100; n++) {
      if (el("status").textContent.startsWith("Загружено ")) {ready=true;break;}
      if (el("status").textContent.startsWith("Ошибка журнала:")) break;
      await new Promise(resolve => setTimeout(resolve,10));
    }
    if (!ready) throw Error("local JSONL import failed: "+el("status").textContent);
    const first = el("tick").textContent;
    const count = Number(el("seek").max)+1;
    if (count < 2) throw Error("not enough committed frames");
    if (el("next").disabled) throw Error("navigation not enabled");
    el("next").click();
    const second = el("tick").textContent;
    const c = el("scene").getBoundingClientRect();
    const viewport = {
      width:window.innerWidth,
      scrollWidth:document.documentElement.scrollWidth,
      canvasWidth:c.width,
      canvasHeight:c.height
    };
    document.documentElement.dataset.realChromeSmoke = JSON.stringify({
      first,second,count,viewport,status:el("status").textContent
    });
  } catch (error) {
    document.documentElement.dataset.realChromeSmoke =
      JSON.stringify({error:String(error && error.message || error)});
  }
});
</script>
""".replace("__TRACE__", literal)
    assert original.count("</body>") == 1
    return original.replace("</body>", injected + "\n</body>")


def main():
    chrome = chrome_binary()
    with tempfile.TemporaryDirectory(prefix="mojum-r09-chrome-") as scratch:
        database = Path(scratch) / "lab.sqlite3"
        env = dict(os.environ, PYTHONPATH=str(ROOT / "src"))
        completed = subprocess.run(
            [sys.executable, "-m", "mojum.sensory_curiosity_lab",
             "--db", str(database), "--ticks", "12", "--watch"],
            cwd=ROOT, env=env, text=True, capture_output=True, timeout=60,
            check=True,
        )
        if not completed.stdout.strip():
            raise AssertionError("isolated CLI did not emit synthetic JSONL")
        page = instrument(VIEWER.read_text(encoding="utf-8"), completed.stdout)
        results = []
        for width, height, mode in [(1280, 800, "desktop"), (390, 844, "mobile")]:
            if mode == "desktop":
                report = inspect_actual_browser(chrome, page, width=width, height=height)
            else:
                report = inspect_actual_mobile_chromedriver(
                    chrome, page, width=width, height=height,
                )
            assert report["count"] >= 2, (mode, report)
            assert report["first"].startswith("Такт "), (mode, report)
            assert report["second"] != report["first"], (mode, report)
            assert "Загружено " in report["status"], (mode, report)
            viewport = report["viewport"]
            assert viewport["canvasWidth"] > 100 and viewport["canvasHeight"] > 60
            if mode == "mobile":
                assert viewport["width"] == 390, viewport
            assert viewport["scrollWidth"] <= viewport["width"] + 2, (mode, viewport)
            results.append({"mode": mode, "frames": report["count"],
                            "canvas_width": round(viewport["canvasWidth"])})
    print(json.dumps({"status": "PASS_REAL_CHROME_R09", "results": results,
                      "data": "ephemeral synthetic PRIVATE fixture only"}))


if __name__ == "__main__":
    main()
