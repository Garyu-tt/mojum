class VersionedCellV3MemoryTests(unittest.TestCase):
    def test_same_real_world_action_as_v2_before_eviction(self):
        v2, v3 = CellExplorer(), CellExplorerV3()
        world = Room(.16, .16)
        state = initial_state(world, .16, .16)
        for tick in range(120):
            sense = Proprioception(
                tick, state.revision, state.x, state.y, tick % 2 == 0,
            )
            a, b = v2.decide(sense), v3.decide(sense)
            self.assertEqual(a["action"], b["action"])
            self.assertEqual((a["dx"], a["dy"]), (b["dx"], b["dy"]))
            next_state, result = advance(
                world, state, tick=tick+1, dx=b["dx"], dy=b["dy"],
                expected_revision=state.revision,
            )
            v2.observe(sense, a, result["blocked"])
            learned = v3.observe(sense, b, result["blocked"])
            self.assertIsNone(learned["evicted_cell"])
            self.assertEqual(learned["total_evictions"], 0)
            state = next_state
        self.assertEqual(v2.records, v3.records)
        self.assertEqual(v2.updates, v3.updates)
        self.assertEqual(
            CellExplorerV3.from_snapshot(v3.snapshot()).snapshot(),
            v3.snapshot(),
        )

    def test_2400_distinct_synthetic_cells_have_exact_bounded_accounting(self):
        # A direct unit-protocol sequence designed to exceed RAM budget;
        # positions are deliberately injected, not generated by a world
        # trajectory. No motor performance/generalization claim is implied.
        model = CellExplorerV3()
        revision = "0" * 64
        first_eviction = None
        for tick in range(2400):
            cue = Proprioception(
                tick, revision, (tick + 1) * STEP_METERS,
                0.0, tick % 7 == 0,
            )
            intent = model.decide(cue)
            outcome = model.observe(cue, intent, False)
            self.assertLessEqual(len(model.records), MAX_CELLS)
            self.assertEqual(outcome["total_updates"], tick + 1)
            if tick == MAX_CELLS:
                first_eviction = outcome
            if tick % 400 == 0:
                self.assertEqual(
                    CellExplorerV3.from_snapshot(model.snapshot()).snapshot(),
                    model.snapshot(),
                )
        self.assertEqual(first_eviction["evicted_cell"], "1:0")
        self.assertEqual(first_eviction["evicted_observations"], 1)
        self.assertEqual(model.updates, 2400)
        self.assertEqual(model.evictions, 2400 - MAX_CELLS)
        self.assertEqual(model.forgotten_observations,
                         2400 - MAX_CELLS)
        self.assertEqual(len(model.records), MAX_CELLS)
        self.assertNotIn("1:0", model.records)
        self.assertIn("2400:0", model.records)
        saved = model.snapshot()
        resumed = CellExplorerV3.from_snapshot(saved)
        for tick in range(2400, 2416):
            cue = Proprioception(
                tick, revision, (tick + 1) * STEP_METERS,
                0.0, tick % 7 == 0,
            )
            self.assertEqual(model.decide(cue), resumed.decide(cue))
            for item in (model, resumed):
                intent = item.decide(cue)
                item.observe(cue, intent, False)
            self.assertEqual(model.snapshot(), resumed.snapshot())
        self.assertEqual(len(model.records), MAX_CELLS)

    def test_recently_observed_old_cell_is_not_evicted_first(self):
        m = CellExplorerV3()
        for tick in range(MAX_CELLS):
            cue = Proprioception(
                tick, "a"*64, (tick+1)*STEP_METERS, 0.0, False,
            )
            m.observe(cue, m.decide(cue), False)
        remembered = Proprioception(
            MAX_CELLS, "a"*64, STEP_METERS, 0.0, True,
        )
        m.observe(remembered, m.decide(remembered), False)
        next_tick = MAX_CELLS+1
        novel = Proprioception(
            next_tick, "a"*64, (next_tick+1)*STEP_METERS, 0.0, False,
        )
        event = m.observe(novel, m.decide(novel), False)
        self.assertEqual(event["evicted_cell"], "2:0")
        self.assertEqual(event["evicted_observations"], 1)
        self.assertIn("1:0", m.records)
        self.assertNotIn("2:0", m.records)
        self.assertEqual(len(m.records), MAX_CELLS)
        self.assertEqual(m.evictions, 1)
        self.assertEqual(m.forgotten_observations, 1)
        self.assertEqual(m.snapshot()["updates"], MAX_CELLS + 2)

    def test_strict_v3_snapshot_rejects_schema_mix_and_accounting_forge(self):
        m = CellExplorerV3()
        cue = Proprioception(0, "0"*64, .16, .16, True)
        m.observe(cue, m.decide(cue), True)
        good = m.snapshot()
        self.assertEqual(CellExplorerV3.from_snapshot(good).snapshot(), good)
        mutations = (
            ("schema", "mojum.developmental.local-cell/2"),
            ("cell_size_m", 0.5),
            ("updates", 2),
            ("last_tick", True),
            ("evictions", -1),
            ("evictions", True),
            ("evictions", 1),
            ("forgotten_observations", 1),
            ("records", {"04:4": {"x+":[1,0]}}),
            ("last_seen_at", {"4:4": -1}),
            ("last_seen_at", {"4:4": True}),
            ("last_seen_at", {"4:4": 8}),
            ("last_seen_at", {}),
        )
        for field, replacement in mutations:
            with self.subTest(field=field, value=replacement):
                changed = deepcopy(good)
                changed[field] = replacement
                with self.assertRaises(CellV3Error):
                    CellExplorerV3.from_snapshot(changed)
        extra = dict(good, **{"silent-trailing-field": 1})
        with self.assertRaises(CellV3Error):
            CellExplorerV3.from_snapshot(extra)

    def test_no_mutable_alias_between_restore_and_original(self):
        m = CellExplorerV3()
        cue = Proprioception(0, "f"*64, .16, .16, True)
        m.observe(cue, m.decide(cue), True)
        checkpoint = m.snapshot()
        alias = CellExplorerV3.from_snapshot(checkpoint)
        alias.records.clear()
        alias.last_seen_at.clear()
        self.assertEqual(m.snapshot(), checkpoint)


class VersionedV3SQLiteTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        self.db = self.root / "source.sqlite3"
        self.target = self.root / "v3.sqlite3"

    def aquarium(self, db=None, *, mode=V3_MODE):
        return Aquarium(db or self.db, SEED, GRAPH, motor_mode=mode)

    def migrate(self, head):
        return transfer_v2b_to_v3(
            self.db, self.target, expected_source_head=head,
            seed=SEED, graph=GRAPH, create_new_journal=True,
        )

    def test_513th_cell_rejects_in_v2_and_evicts_in_v3(self):
        v2, v3 = CellExplorer(), CellExplorerV3()
        for tick in range(MAX_CELLS):
            cue = Proprioception(tick, "0" * 64, .04 * tick, 1., False)
            v2.observe(cue, v2.decide(cue), False)
            v3.observe(cue, v3.decide(cue), False)
        before = v2.snapshot()
        after = Proprioception(MAX_CELLS, "0" * 64, .04 * MAX_CELLS, 1., False)
        with self.assertRaisesRegex(LocalCellError, "capacity exhausted"):
            v2.observe(after, v2.decide(after), False)
        self.assertEqual(v2.snapshot(), before)
        receipt = v3.observe(after, v3.decide(after), False)
        self.assertEqual(receipt["evicted_cell"], "0:25")
        self.assertEqual(receipt["total_evictions"], 1)
        self.assertEqual(receipt["total_forgotten_observations"], 1)
        self.assertEqual(len(v3.snapshot()["records"]), MAX_CELLS)

    def test_failed_append_cannot_adopt_eviction_and_cold_replay_matches(self):
        # Exercise actual SQLite/world replay with a test-only smaller cap.
        with patch("mojum.cell_policy_v3.MAX_CELLS", 4):
            with self.aquarium() as rover:
                for _ in range(40):
                    candidate, _, _ = rover._calculate(None, None)
                    if candidate["developmental"]["learning"]["evicted_cell"] is not None:
                        break
                    rover.step()
                else:
                    self.fail("standard room never exercised the test eviction cap")
                before = rover.checkpoint()
                count = rover.store.count()
                with patch.object(rover.store, "append", side_effect=NoosphereError("simulated failure")):
                    with self.assertRaises(NoosphereError):
                        rover.step()
                self.assertEqual(rover.checkpoint(), before)
                self.assertEqual(rover.store.count(), count)
                self.assertEqual(rover.step(), candidate)
                expected = rover.checkpoint()
                self.assertEqual(expected["developmental_state"]["evictions"], 1)
            with self.aquarium() as resumed:
                self.assertEqual(resumed.checkpoint(), expected)
                self.assertEqual(resumed.store.count(), count + 1)

    def test_v2b_cannot_be_opened_as_v3_and_transfer_preserves_source(self):
        with self.aquarium(mode=V2B_MODE) as origin:
            for _ in range(60):
                origin.step()
            expected = origin.checkpoint()
        with closing(sqlite3.connect(self.db)) as connection:
            self.assertEqual(connection.execute("PRAGMA journal_mode=DELETE").fetchone()[0], "delete")
        before = self.db.read_bytes()
        with self.assertRaisesRegex(AquariumError, "mismatch"):
            self.aquarium()
        self.assertEqual(self.db.read_bytes(), before)
        report = self.migrate(expected["journal_head"])
        self.assertEqual(report["compared_frames"], 60)
        self.assertEqual(report["destination_policy_schema"], SCHEMA)
        self.assertEqual(self.db.read_bytes(), before)
        self.assertEqual(inspect_journal(self.target)["format"], V3_MODE)
        with self.aquarium(self.target) as imported:
            checkpoint = imported.checkpoint()
            self.assertEqual(checkpoint["world_revision"], expected["world_revision"])
            self.assertEqual(checkpoint["developmental_state"]["records"],
                             expected["developmental_state"]["records"])
            self.assertEqual(checkpoint["developmental_state"]["evictions"], 0)
            self.assertEqual(checkpoint["journal_head"], report["destination_head"])
            imported.step()

    def test_transfer_refuses_if_target_would_evict_source_evidence(self):
        with self.aquarium(mode=V2B_MODE) as origin:
            for _ in range(25):
                origin.step()
            head = origin.checkpoint()["journal_head"]
        before = self.db.read_bytes()
        with patch("mojum.cell_policy_v3.MAX_CELLS", 4):
            with self.assertRaisesRegex(TransferError, "retention changed"):
                self.migrate(head)
        self.assertFalse(self.target.exists())
        self.assertEqual(self.db.read_bytes(), before)

    @unittest.skipUnless(SOURCE115 and SOURCE122, "requires pinned native #115 and #122")
    def test_native_v3_reopens_migrated_history_and_appends_the_same_chain(self):
        def run_native(tree, database, ticks, mode):
            root = Path(tree).resolve()
            raw = subprocess.check_output(
                [sys.executable, "-m", "mojum.aquarium", "--db", str(database),
                 "--ticks", str(ticks), "--exploration-mode", "goal_free",
                 "--developmental-policy", mode],
                cwd=root, env=dict(os.environ, PYTHONPATH=str(root / "src")),
                encoding="utf-8", timeout=60,
            )
            return json.loads(raw)

        before = run_native(SOURCE115, self.db, 120, "local_cell_v2")
        old_wire = self.db.read_bytes()
        cli = subprocess.check_output(
            [sys.executable, "-m", "mojum.migration_v2b_v3",
             "--source", str(self.db), "--destination", str(self.target),
             "--genome", str(ROOT / "examples/genesis_seed.json"),
             "--graph", str(ROOT / "examples/first_loop.json"),
             "--expected-source-head", before["journal_head"], "--create-new-journal"],
            cwd=ROOT, env=dict(os.environ, PYTHONPATH=str(ROOT / "src")),
            encoding="utf-8", timeout=90,
        )
        receipt = json.loads(cli)
        resumed = run_native(SOURCE122, self.target, 0, V3_MODE)
        self.assertEqual(resumed["journal_head"], receipt["destination_head"])
        row = run_native(SOURCE122, self.target, 1, V3_MODE)
        self.assertEqual(row["tick"], 121)
        self.assertEqual(row, run_native(SOURCE122, self.root / "control.sqlite3", 121, V3_MODE))
        self.assertEqual(self.db.read_bytes(), old_wire)


