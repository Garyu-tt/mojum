"""R0.14 optional local-cell v3 deterministic eviction and SQLite replay QA.

Synthetic CPU-only tests. 2400 unique cells exercise the in-memory retention
protocol, NOT an assertion of a physically coherent 2400-step trajectory.
"""
from copy import deepcopy
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from mojum.aquarium import Aquarium, AquariumError
from mojum.cell_policy_v2 import CellExplorer
from mojum.cell_policy_v3 import (
    CellExplorerV3, CellV3Error, MAX_CELLS, SCHEMA, LEARNING_SCHEMA,
)
from mojum.developmental_policy import Proprioception, STEP_METERS
from mojum.world_room import Room, advance, initial_state


ROOT = Path(__file__).resolve().parents[1]
SEED = json.loads((ROOT / "examples/genesis_seed.json").read_text(encoding="utf-8"))
GRAPH = json.loads((ROOT / "examples/first_loop.json").read_text(encoding="utf-8"))


class VersionedCellV3MemoryTests(unittest.TestCase):
    def test_same_real_world_action_as_v2_before_eviction(self):
        v2, v3 = CellExplorer(), CellExplorerV3()
        world = Room(.16, .16)
        state = initial_state(world, .16, .16)
        for tick in range(120):
            sense = Proprioception(
                tick, state.revision, state.x, state.y, tick % 2 == 0,
            )
            a, b = v2.decide(sense), v3.decide(sense)
            self.assertEqual(a["action"], b["action"])
            self.assertEqual((a["dx"], a["dy"]), (b["dx"], b["dy"]))
            next_state, result = advance(
                world, state, tick=tick+1, dx=b["dx"], dy=b["dy"],
                expected_revision=state.revision,
            )
            v2.observe(sense, a, result["blocked"])
            learned = v3.observe(sense, b, result["blocked"])
            self.assertIsNone(learned["evicted_cell"])
            self.assertEqual(learned["total_evictions"], 0)
            state = next_state
        self.assertEqual(v2.records, v3.records)
        self.assertEqual(v2.updates, v3.updates)
        self.assertEqual(
            CellExplorerV3.from_snapshot(v3.snapshot()).snapshot(),
            v3.snapshot(),
        )

    def test_2400_distinct_synthetic_cells_have_exact_bounded_accounting(self):
        # A direct unit-protocol sequence designed to exceed RAM budget;
        # positions are deliberately injected, not generated by a world
        # trajectory. No motor performance/generalization claim is implied.
        model = CellExplorerV3()
        revision = "0" * 64
        first_eviction = None
        for tick in range(2400):
            cue = Proprioception(
                tick, revision, (tick + 1) * STEP_METERS,
                0.0, tick % 7 == 0,
            )
            intent = model.decide(cue)
            outcome = model.observe(cue, intent, False)
            self.assertLessEqual(len(model.records), MAX_CELLS)
            self.assertEqual(outcome["total_updates"], tick + 1)
            if tick == MAX_CELLS:
                first_eviction = outcome
            if tick % 400 == 0:
                self.assertEqual(
                    CellExplorerV3.from_snapshot(model.snapshot()).snapshot(),
                    model.snapshot(),
                )
        self.assertEqual(first_eviction["evicted_cell"], "1:0")
        self.assertEqual(first_eviction["evicted_observations"], 1)
        self.assertEqual(model.updates, 2400)
        self.assertEqual(model.evictions, 2400 - MAX_CELLS)
        self.assertEqual(model.forgotten_observations,
                         2400 - MAX_CELLS)
        self.assertEqual(len(model.records), MAX_CELLS)
        self.assertNotIn("1:0", model.records)
        self.assertIn("2400:0", model.records)
        saved = model.snapshot()
        resumed = CellExplorerV3.from_snapshot(saved)
        for tick in range(2400, 2416):
            cue = Proprioception(
                tick, revision, (tick + 1) * STEP_METERS,
                0.0, tick % 7 == 0,
            )
            self.assertEqual(model.decide(cue), resumed.decide(cue))
            for item in (model, resumed):
                intent = item.decide(cue)
                item.observe(cue, intent, False)
            self.assertEqual(model.snapshot(), resumed.snapshot())
        self.assertEqual(len(model.records), MAX_CELLS)

    def test_recently_observed_old_cell_is_not_evicted_first(self):
        m = CellExplorerV3()
        for tick in range(MAX_CELLS):
            cue = Proprioception(
                tick, "a"*64, (tick+1)*STEP_METERS, 0.0, False,
            )
            m.observe(cue, m.decide(cue), False)
        remembered = Proprioception(
            MAX_CELLS, "a"*64, STEP_METERS, 0.0, True,
        )
        m.observe(remembered, m.decide(remembered), False)
        next_tick = MAX_CELLS+1
        novel = Proprioception(
            next_tick, "a"*64, (next_tick+1)*STEP_METERS, 0.0, False,
        )
        event = m.observe(novel, m.decide(novel), False)
        self.assertEqual(event["evicted_cell"], "2:0")
        self.assertEqual(event["evicted_observations"], 1)
        self.assertIn("1:0", m.records)
        self.assertNotIn("2:0", m.records)
        self.assertEqual(len(m.records), MAX_CELLS)
        self.assertEqual(m.evictions, 1)
        self.assertEqual(m.forgotten_observations, 1)
        self.assertEqual(m.snapshot()["updates"], MAX_CELLS + 2)

    def test_strict_v3_snapshot_rejects_schema_mix_and_accounting_forge(self):
        m = CellExplorerV3()
        cue = Proprioception(0, "0"*64, .16, .16, True)
        m.observe(cue, m.decide(cue), True)
        good = m.snapshot()
        self.assertEqual(CellExplorerV3.from_snapshot(good).snapshot(), good)
        mutations = (
            ("schema", "mojum.developmental.local-cell/2"),
            ("cell_size_m", 0.5),
            ("updates", 2),
            ("last_tick", True),
            ("evictions", -1),
            ("evictions", True),
            ("evictions", 1),
            ("forgotten_observations", 1),
            ("records", {"04:4": {"x+":[1,0]}}),
            ("last_seen_at", {"4:4": -1}),
            ("last_seen_at", {"4:4": True}),
            ("last_seen_at", {"4:4": 8}),
            ("last_seen_at", {}),
        )
        for field, replacement in mutations:
            with self.subTest(field=field, value=replacement):
                changed = deepcopy(good)
                changed[field] = replacement
                with self.assertRaises(CellV3Error):
                    CellExplorerV3.from_snapshot(changed)
        extra = dict(good, **{"silent-trailing-field": 1})
        with self.assertRaises(CellV3Error):
            CellExplorerV3.from_snapshot(extra)

    def test_no_mutable_alias_between_restore_and_original(self):
        m = CellExplorerV3()
        cue = Proprioception(0, "f"*64, .16, .16, True)
        m.observe(cue, m.decide(cue), True)
        checkpoint = m.snapshot()
        alias = CellExplorerV3.from_snapshot(checkpoint)
        alias.records.clear()
        alias.last_seen_at.clear()
        self.assertEqual(m.snapshot(), checkpoint)


class VersionedV3SQLiteTests(unittest.TestCase):
    def setUp(self):
        t = tempfile.TemporaryDirectory()
        self.addCleanup(t.cleanup)
        self.root = Path(t.name)
        self.db = self.root / "synthetic-v3.sqlite3"
        self.room = Room(.16, .16)

    def open(self, policy="local_cell_v3"):
        return Aquarium(
            self.db, SEED, GRAPH, room=self.room, start=(.16,.16),
            exploration_mode="goal_free", developmental_policy=policy,
        )

    def test_v3_new_bootstrap_600_tick_cold_replay_and_legacy_v2_refusal(self):
        with self.open() as m:
            self.assertEqual(m.manifest["developmental_schema"], SCHEMA)
            self.assertEqual(m.manifest["developmental_policy"], "local_cell_v3")
            for _ in range(600):
                frame = m.step()
                self.assertEqual(frame["developmental"]["schema"], SCHEMA)
                self.assertEqual(
                    frame["developmental"]["learning"]["schema"],
                    LEARNING_SCHEMA,
                )
                self.assertEqual(frame["brain"]["status"], "UNIMPLEMENTED")
            before = m.checkpoint()
            self.assertEqual(m.store.count(), 601)
            self.assertEqual(before["developmental_state"]["updates"], 600)
            self.assertEqual(before["developmental_state"]["evictions"], 0)
            self.assertEqual(before["developmental_state"]["schema"], SCHEMA)
        for other in ("legacy", "local_cell_v2"):
            with self.subTest(policy=other):
                with self.assertRaisesRegex(
                    AquariumError, "seed, room, graph or clock",
                ):
                    with self.open(other):
                        pass
        with self.open() as restart:
            self.assertEqual(restart.checkpoint(), before)
            restart.step()
            final = restart.checkpoint()
            self.assertEqual(final["developmental_state"]["updates"], 601)
        with self.open() as restart:
            self.assertEqual(restart.checkpoint(), final)

    def test_v2_journal_never_reinterpreted_as_v3(self):
        with self.open("local_cell_v2") as v2:
            self.assertNotIn("evictions", v2.explorer.snapshot())
            self.assertEqual(v2.manifest["developmental_policy"],
                             "local_cell_v2")
            for _ in range(8):
                v2.step()
            checkpoint = v2.checkpoint()
        with self.assertRaisesRegex(
            AquariumError, "seed, room, graph or clock",
        ):
            with self.open("local_cell_v3"):
                pass
        with self.open("local_cell_v2") as reopened:
            self.assertEqual(reopened.checkpoint(), checkpoint)

    def test_v3_durable_append_before_ram_adoption_recovers_once(self):
        with self.open() as before:
            checkpoint = before.checkpoint()
            original = before.store.append

            def raise_after_commit(event, *, expected_head):
                written = original(event, expected_head=expected_head)
                self.assertEqual(written, before.store.head())
                raise RuntimeError("synthetic postcommit stop")

            with patch.object(before.store, "append",
                              side_effect=raise_after_commit):
                with self.assertRaisesRegex(RuntimeError, "postcommit"):
                    before.step()
            self.assertEqual(before.tick, 0)
            self.assertEqual(
                before.explorer.snapshot(), checkpoint["developmental_state"],
            )
            self.assertEqual(before.store.count(), 2)
            with self.assertRaisesRegex(
                AquariumError, "stale or unadopted",
            ):
                before.checkpoint()
        with self.open() as restart:
            self.assertEqual(restart.tick, 1)
            self.assertEqual(restart.explorer.updates, 1)
            self.assertEqual(restart.store.count(), 2)


if __name__ == "__main__":
    unittest.main()
