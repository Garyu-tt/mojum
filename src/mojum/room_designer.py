"""Materialize the bundled standalone offline point-room designer."""
from __future__ import annotations

import argparse
import hashlib
from importlib.resources import files
import json
import os
from pathlib import Path
import tempfile


SCHEMA = "mojum.room-designer.export/1"


class RoomDesignerError(ValueError):
    """The requested designer destination is already occupied."""


def export_designer(destination):
    """Publish the complete bundled editor to a new path without replacement.

    The resource is generated by tools/package_room_designer.py. No room,
    journal or trace is opened, and no browser or server is started.
    """
    path = Path(destination)
    if path.exists() or path.is_symlink():
        raise RoomDesignerError("designer output already exists; choose a new path")
    data = files("mojum").joinpath("data", "room_designer.html").read_bytes()
    descriptor, temporary_name = tempfile.mkstemp(prefix=".mojum-designer-", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as output:
            descriptor = None
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
        # A reader sees complete bytes, and a competing creator cannot be
        # overwritten between the initial check and this exclusive link.
        try:
            os.link(temporary, path)
        except FileExistsError as exc:
            raise RoomDesignerError("designer output already exists; choose a new path") from exc
    finally:
        if descriptor is not None:
            os.close(descriptor)
        temporary.unlink(missing_ok=True)
    return {"schema": SCHEMA, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write the standalone offline point-room designer")
    parser.add_argument("--output", type=Path, required=True,
                        help="new HTML file to create; existing paths are never overwritten")
    args = parser.parse_args(argv)
    try:
        receipt = export_designer(args.output)
    except RoomDesignerError as exc:
        parser.error(str(exc))
    except OSError:
        parser.error("cannot write designer; check the output directory and permissions")
    print(json.dumps(receipt, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
